export function getScientistDialogue(avatarId, type = 'correct', streak = 0) {
  const scientist = SCIENTIST_DIALOGUES[avatarId] || SCIENTIST_DIALOGUES.fleming;
  let pool = scientist.correct;

  if (type === 'incorrect') {
    pool = scientist.incorrect;
  } else if (streak >= 3) {
    pool = scientist.streak;
  }

  const text = pool[Math.floor(Math.random() * pool.length)];
  return {
    name: scientist.name,
    text,
    avatarUrl: `/avatars/avatar_${avatarId || 'fleming'}.png`,
  };
}
